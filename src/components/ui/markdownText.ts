/**
 * 마크다운 원문에서 문법 기호를 걷어낸 한 줄 요약.
 *
 * <p>목록 카드처럼 몇 줄만 잘라 보여 주는 자리에 쓴다. 그런 자리에 마크다운을 그대로 렌더하면
 * 제목이 카드보다 커지고 목록 마커가 줄을 먹는다. 그렇다고 원문을 그대로 찍으면 `##` 이나
 * 백틱이 글자로 보인다 — 기호만 지우고 내용을 남긴다.</p>
 *
 * <p>본문을 제대로 보여 주는 자리(상세·미리보기)는 이 함수가 아니라 Markdown 컴포넌트를 쓴다.</p>
 */
export function markdownToText(src: string | null | undefined): string {
  if (!src) return ''
  return (
    src
      // 코드 펜스는 통째로 — 안쪽 내용을 요약에 끌어오면 무슨 말인지 알 수 없다.
      .replace(/```[\s\S]*?```/g, ' ')
      .replace(/`([^`]+)`/g, '$1')
      // 이미지는 대체 텍스트조차 요약에서는 잡음이라 지우고, 링크는 글자만 남긴다.
      .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      // 헤딩·인용·목록 마커는 줄머리에서만 지운다(문장 중간의 #, - 는 내용이다).
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      .replace(/^\s{0,3}>\s?/gm, '')
      .replace(/^\s{0,3}[-*+]\s+/gm, '')
      .replace(/^\s{0,3}\d+\.\s+/gm, '')
      .replace(/^\s{0,3}([-*_])\s*\1\s*\1[\s-*_]*$/gm, ' ')
      // 강조는 쌍으로 감싼 것만 — 스네이크 케이스 식별자(user_id)를 건드리지 않는다.
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/__([^_]+)__/g, '$1')
      .replace(/\*([^*\n]+)\*/g, '$1')
      // 표 구분선(| --- |)만 지우고 셀 구분자는 공백으로 바꿔 내용을 잇는다.
      .replace(/^\s*\|?[\s:|-]*\|[\s:|-]*$/gm, ' ')
      .replace(/\|/g, ' ')
      // 편집기가 저장할 때 씌운 껍데기를 벗긴다 — 요약은 렌더러를 거치지 않아
      // 그냥 두면 `&lt;`, `\_` 가 글자 그대로 목록에 보인다.
      .replace(/\\([\\`*_{}[\]()#+\-.!>|~])/g, '$1')
      .replace(
        /&(lt|gt|amp|quot|apos|nbsp|#39|#x27);/gi,
        (_, e: string) => ENTITIES[e.toLowerCase()] ?? _,
      )
      .replace(/\s+/g, ' ')
      .trim()
  )
}

const ENTITIES: Record<string, string> = {
  lt: '<',
  gt: '>',
  amp: '&',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  '#39': "'",
  '#x27': "'",
}
